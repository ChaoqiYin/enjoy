import assert from 'node:assert/strict';
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { extname, join } from 'node:path';
import ts from 'typescript';

// What this interface is allowed to ask of the application it runs inside.
//
// Tauri answers a call into its own API — closing a window, opening a folder
// picker, showing a file in its folder — only if a capability file has granted
// the permission that covers it. The call and the grant are written in two
// places nothing connects, and the grant reads plausible while covering
// something else: `core:window:default` sounds like "what a window is normally
// allowed to do" and is in fact a list of getters, so `close()` was refused at
// runtime — on the one build that shipped it — with the refusal swallowed by a
// `void`. The window did not close and nothing was said. That is the same shape
// as the names `check-commands.mjs` and `check-version.mjs` exist for, and this
// is the same kind of check.
//
// The reaches are in one file. `check-commands.mjs` keeps them there, so
// `shared/api.ts` is the whole of the interface's own address for Tauri, and
// reading it reads every reach.
//
// Of the two facts this needs, only one is in the repository. What a reach
// requires is Tauri's own list, kept in `needs` below and named the way Tauri
// names it (`permissions/*/autogenerated/reference.md` in the crate is the same
// list). What is granted is the capability files, read here as they are
// written. A reach written in a form this file does not read is a failure
// rather than a silence, which is the only thing that keeps `needs` complete.
//
// A build leaves Tauri's manifest of what every permission set contains in
// `src-tauri/gen/`, and where that is present the grants are expanded through
// it: a permission is then checked against what the sets really carry rather
// than against its own name appearing in a file. It is a generated artefact and
// so not in the repository; on a machine where the application has not been
// built, that half is skipped and says so.

const seam = join('frontend', 'src', 'shared', 'api.ts');
const capabilities = join('src-tauri', 'capabilities');
const manifest = join('src-tauri', 'gen', 'schemas', 'acl-manifests.json');

/** A reach that needs no permission: a pure function, or the application's own backend, which the ACL does not stand in front of. */
const nothing = null;

/**
 * Every Tauri package the interface may reach through, and what each function
 * in it needs. A package that is not here, or a function of one that is not, is
 * a failure rather than a skip.
 */
const needs = {
  '@tauri-apps/api/core': {
    invoke: nothing,
    convertFileSrc: nothing,
    isTauri: nothing,
  },
  '@tauri-apps/api/event': {
    listen: 'core:event:allow-listen',
  },
  // Nothing reaches through this package, and the entries stay as what a reach
  // would need rather than as what is used. The interface stopped touching its
  // own window when the close became the backend's decision (`crate::closing`):
  // holding a close, asking about it and closing afterwards are all on the other
  // side of the seam now, so no permission over the window is granted either.
  //
  // An entry here is not a grant — it is the other half of the check, the fact
  // Tauri owns. Adding a reach back through this package is exactly the mistake
  // the table exists to catch, and `core:window:allow-destroy` is the one to be
  // careful with: Tauri prevents a close whenever the window has a close-requested
  // listener, so `close()` can never go through on a window that has ever
  // subscribed, and `destroy()` is the way out.
  '@tauri-apps/api/window': {
    getCurrentWindow: nothing,
    onCloseRequested: 'core:event:allow-listen',
    destroy: 'core:window:allow-destroy',
  },
  '@tauri-apps/plugin-dialog': {
    open: 'dialog:allow-open',
  },
  '@tauri-apps/plugin-opener': {
    revealItemInDir: 'opener:allow-reveal-item-in-dir',
  },
};

const failures = [];

function parse(path) {
  return ts.createSourceFile(
    path,
    readFileSync(path, 'utf8'),
    ts.ScriptTarget.Latest,
    true,
    extname(path) === '.tsx' ? ts.ScriptKind.TSX : ts.ScriptKind.TS,
  );
}

/** The packages the seam imports as values, by the name each was given. */
function bindings() {
  const bound = new Map();
  for (const statement of parse(seam).statements) {
    if (!ts.isImportDeclaration(statement)) continue;
    // A type-only import names a signature and is erased before anything runs.
    if (statement.importClause?.isTypeOnly) continue;
    const from = statement.moduleSpecifier;
    if (!ts.isStringLiteral(from) || !from.text.startsWith('@tauri-apps/'))
      continue;
    if (!(from.text in needs)) {
      failures.push(
        `${seam}: reaches through ${from.text}, which nothing in this check accounts for`,
      );
      continue;
    }
    const named = statement.importClause?.namedBindings;
    if (named && ts.isNamedImports(named)) {
      for (const element of named.elements) bound.set(element.name.text, from.text);
    }
  }
  return bound;
}

/**
 * What one call is, when the thing being called is one of those names.
 *
 * Three shapes are read, and they are the three the seam uses: the function
 * itself (`isTauri()`), the function called for an object it answers with
 * (`getCurrentWindow().close()`), and a property of that object read without a
 * call. Anything else — a window kept in a variable, a function passed on — is
 * reported by [`reaches`] instead: what it would need is knowable only from
 * what the object is, and this file does not work that out.
 */
function call(node, bound) {
  const callee = node.expression;
  if (ts.isIdentifier(callee) && bound.has(callee.text)) {
    return { package: bound.get(callee.text), name: callee.text };
  }
  if (
    ts.isPropertyAccessExpression(callee) &&
    ts.isCallExpression(callee.expression) &&
    ts.isIdentifier(callee.expression.expression) &&
    bound.has(callee.expression.expression.text)
  ) {
    return {
      package: bound.get(callee.expression.expression.text),
      name: callee.name.text,
    };
  }
  return null;
}

/** What one reach needs, reporting a reach the table does not carry. */
function permissionFor(packageName, name) {
  const table = needs[packageName];
  if (!(name in table)) {
    failures.push(
      `${seam}: ${packageName} is reached through ${name}(), which this check has no permission for`,
    );
    return;
  }
  return table[name];
}

/**
 * Whether an identifier is where a name is introduced rather than where it is
 * used. A reach is found at the call, not at the name of the thing being
 * called: `open` is a name in `{ open: ... }` and in the import that bound it,
 * and a use in `open()`.
 *
 * A shorthand property is the one that reads both ways, and it is a use: `open`
 * on its own in an object literal is the imported function being passed on,
 * which is a reach this check cannot follow.
 */
function isName(node) {
  const parent = node.parent;
  if (ts.isShorthandPropertyAssignment(parent)) return false;
  return ts.isImportSpecifier(parent) || parent.name === node;
}

/** Every reach the seam makes, and every use of a Tauri name this file cannot read as one. */
function reaches() {
  const bound = bindings();
  const found = new Set();
  const visit = (node) => {
    if (ts.isCallExpression(node)) {
      const target = call(node, bound);
      if (target) {
        const permission = permissionFor(target.package, target.name);
        if (permission) found.add(permission);
      }
    }
    // A name imported from a Tauri package that is not being called, and not
    // being called for what it answers with either, is a reach this check
    // cannot follow to a permission.
    if (ts.isIdentifier(node) && bound.has(node.text) && !isName(node)) {
      const parent = node.parent;
      const called = ts.isCallExpression(parent) && parent.expression === node;
      if (!called) {
        failures.push(
          `${seam}: ${node.text} is used without being called, so what it reaches for is not readable here`,
        );
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(parse(seam));
  return found;
}

/** The permissions the capabilities grant, as the identifiers they are written as. */
function granted() {
  const grants = [];
  for (const entry of readdirSync(capabilities, { withFileTypes: true })) {
    if (!entry.isFile() || !entry.name.endsWith('.json')) continue;
    const path = join(capabilities, entry.name);
    const capability = JSON.parse(readFileSync(path, 'utf8'));
    for (const permission of capability.permissions ?? [])
      grants.push({ permission, path });
  }
  return grants;
}

/**
 * What a set stands for, according to the manifest Tauri generated.
 *
 * A permission lives in a namespace (`core:window`, `dialog`) and a name, and a
 * name inside a set is written bare when it belongs to the set's own namespace
 * and whole when it does not — which is the whole of the rule this needs.
 */
function expand(manifests, identifier) {
  const parts = identifier.split(':');
  const name = parts.pop();
  const namespace = parts.join(':');
  const manifest = manifests[namespace];
  if (!manifest) return null;
  const entries =
    name === 'default'
      ? manifest.default_permission?.permissions
      : manifest.permissions?.[name]
        ? []
        : manifest.permission_sets?.[name]?.permissions;
  if (!entries) return null;
  // A permission stands for itself. A set stands for what it names, told apart
  // by whether the name belongs to the set's own namespace, and reached into
  // again for the sets that name sets.
  const expanded = new Set([identifier]);
  for (const entry of entries) {
    const whole = entry.includes(':') ? entry : `${namespace}:${entry}`;
    const deeper = expand(manifests, whole);
    if (!deeper) {
      failures.push(`${identifier} names ${whole}, which Tauri does not know`);
      continue;
    }
    for (const each of deeper) expanded.add(each);
  }
  return expanded;
}

const needed = reaches();
const grants = granted();
const names = new Set(grants.map((grant) => grant.permission));

for (const permission of needed) {
  if (!names.has(permission)) {
    failures.push(
      `the interface reaches for ${permission}, and no capability grants it: ${[...names].sort().join(', ')}`,
    );
  }
}

if (existsSync(manifest)) {
  const manifests = JSON.parse(readFileSync(manifest, 'utf8'));
  const held = new Set();
  for (const { permission, path } of grants) {
    const expanded = expand(manifests, permission);
    if (!expanded) {
      failures.push(`${path}: ${permission} is not a permission or a set Tauri knows`);
      continue;
    }
    for (const entry of expanded) held.add(entry);
  }
  for (const permission of needed) {
    if (!held.has(permission)) {
      failures.push(
        `the interface reaches for ${permission}, and what the capabilities grant does not carry it`,
      );
    }
  }
}

assert.equal(failures.length, 0, failures.join('\n'));

console.log(
  `Every reach into the application is granted: ${needed.size} permissions across ${grants.length} grants` +
    (existsSync(manifest)
      ? ', expanded through Tauri\'s manifest'
      : '; Tauri\'s manifest is not here, so the grants were read as written'),
);
